/**
 * Generates dist/sw.js after `vite build`. All essential assets (hashed JS/CSS,
 * fonts, icons, manifest and the app shell) are explicitly precached so the
 * second load works with no network at all.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');

async function walk(dir, prefix = '') {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = `${prefix}${entry.name}`;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...await walk(full, `${relative}/`));
    else if (entry.isFile()) files.push({ relative, full });
  }
  return files;
}

const index = path.join(dist, 'index.html');
try { await fs.access(index); } catch { throw new Error('dist/index.html missing — run vite build first'); }

const files = (await walk(dist)).filter((f) => {
  if (f.relative === 'sw.js' || f.relative.endsWith('.map') || f.relative.endsWith('.DS_Store')) return false;
  return !f.relative.endsWith('.txt') || f.relative === 'robots.txt';
});

const hash = crypto.createHash('sha256');
for (const file of files.sort((a, b) => a.relative.localeCompare(b.relative))) {
  const stat = await fs.stat(file.full);
  hash.update(`${file.relative}:${stat.size}:`);
}
const version = hash.digest('hex').slice(0, 12);

const urls = ['/', '/index.html', ...files.map((f) => `/${f.relative}`)];

const sw = `/* MathFlow service worker — generated by scripts/build-sw.mjs. Do not edit. */
const VERSION = '${version}';
const CACHE = 'mathflow-' + VERSION;
const PRECACHE = ${JSON.stringify(urls, null, 2)};

const OFFLINE_PAGE = \`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>MathFlow — offline</title><style>body{font-family:system-ui,sans-serif;background:#0b1f31;color:#f4efe3;display:grid;place-content:center;min-height:100vh;text-align:center;padding:24px;margin:0}h1{color:#35c9bd}p{max-width:34ch;line-height:1.6}</style></head><body><h1>MathFlow</h1><p>This page is not cached yet. Open MathFlow once while online, then it will work offline.</p><p dir="rtl" lang="ar">افتح ماث فلو مرة واحدة وأنت متصل بالإنترنت، ثم سيعمل دون اتصال.</p></body></html>\`;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(PRECACHE);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith('mathflow-') && key !== CACHE).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === '/sw.js') return;

  // OCR is the only online feature: never serve a cached/fake recognition result.
  if (url.pathname.startsWith('/api/')) {
    event.respondWith(fetch(request).catch(() => new Response(JSON.stringify({ code: 'ocr.network', offline: true }), {
      status: 503, headers: { 'Content-Type': 'application/json' }
    })));
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response && response.ok) {
          const cache = await caches.open(CACHE);
          await cache.put('/index.html', response.clone());
        }
        return response;
      } catch {
        const cached = await caches.match('/index.html') || await caches.match('/');
        return cached || new Response(OFFLINE_PAGE, { status: 200, headers: { 'Content-Type': 'text/html; charset=utf-8' } });
      }
    })());
    return;
  }

  event.respondWith((async () => {
    const cached = await caches.match(request);
    if (cached) return cached;
    try {
      const response = await fetch(request);
      if (response && response.ok && response.type === 'basic') {
        const cache = await caches.open(CACHE);
        await cache.put(request, response.clone());
      }
      return response;
    } catch {
      return new Response('', { status: 503, statusText: 'Offline' });
    }
  })());
});
`;

await fs.writeFile(path.join(dist, 'sw.js'), sw, 'utf8');
console.log(`[sw] generated sw.js (${version}) with ${urls.length} precache entries`);
